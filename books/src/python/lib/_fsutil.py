#!/usr/bin/env python3
"""Filesystem helpers for the delivery toolchain.

Every helper converts an ``OSError`` (missing file, permissions, bad
directory) into a single-line, user-facing ``sys.exit`` message, so the
callers stay free of per-call try/except noise.
"""
from __future__ import annotations

import contextlib
import io
import json
import os
import sys
from typing import Any


def _die(action: str, path: str, exc: Exception) -> None:
    sys.exit(f'error: cannot {action} {path}: {exc}')


def read_text(path: str) -> str:
    """Return the whole UTF-8 file, or exit with a clean message."""
    try:
        with open(path, encoding='utf-8') as fh:
            return fh.read()
    except OSError as exc:
        _die('read', path, exc)
    raise AssertionError('unreachable')  # pragma: no cover


def read_lines(path: str) -> list[str]:
    """Return the file as lines, or exit with a clean message."""
    try:
        with open(path, encoding='utf-8') as fh:
            return fh.readlines()
    except OSError as exc:
        _die('read', path, exc)
    raise AssertionError('unreachable')  # pragma: no cover


def read_text_raw(path: str) -> str:
    """Read UTF-8 text; OSError propagates so callers keep their handlers."""
    try:
        with open(path, encoding='utf-8') as fh:
            return fh.read()
    except OSError as exc:
        exc.add_note(f'while reading {path}')
        raise


def read_lines_raw(path: str) -> list[str]:
    """Read lines; OSError propagates so callers keep their handlers."""
    try:
        with open(path, encoding='utf-8') as fh:
            return fh.readlines()
    except OSError as exc:
        exc.add_note(f'while reading {path}')
        raise


# Test isolation: with BOOK_TEST_GUARD=<book root> set, the suite may not write
# into the real manuscript or artifacts. Fixture books live in temp dirs and are
# unaffected; a stray write against the checked-out book raises instead of
# silently replacing written prose with a fresh skeleton.
# artifacts under dist/ are regenerated by any build, so tests may rebuild them;
# the manuscript is the one thing a test cannot reconstruct, so it is guarded.
GUARDED_SUFFIXES = ('data/manuscript',)


def _guard_write(path: str) -> None:
    root = os.environ.get('BOOK_TEST_GUARD')
    if not root:
        return
    target = os.path.abspath(path)
    for suffix in GUARDED_SUFFIXES:
        guarded = os.path.join(os.path.abspath(root), suffix)
        if target == guarded or target.startswith(guarded + os.sep):
            raise RuntimeError(f'test isolation: refusing to write {path} '
                               f'(guarded by BOOK_TEST_GUARD={root})')


def write_text(path: str, text: str) -> None:
    """Write UTF-8 text, or exit with a clean message."""
    _guard_write(path)
    try:
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(text)
    except OSError as exc:
        _die('write', path, exc)


def load_json(path: str) -> Any:
    """Load a UTF-8 JSON file, or exit with a clean message."""
    try:
        with open(path, encoding='utf-8') as fh:
            return json.load(fh)
    except OSError as exc:
        _die('read', path, exc)
    except json.JSONDecodeError as exc:
        sys.exit(f'error: invalid JSON in {path}: {exc}')
    raise AssertionError('unreachable')  # pragma: no cover


def dump_json(path: str, payload: Any) -> None:
    """Write a JSON payload, or exit with a clean message."""
    try:
        with open(path, 'w', encoding='utf-8') as fh:
            json.dump(payload, fh, ensure_ascii=False, indent=2)
            fh.write('\n')
    except OSError as exc:
        _die('write', path, exc)


def ensure_dir(path: str) -> None:
    """Create the directory for ``path`` if needed, or exit cleanly."""
    target = os.path.dirname(os.path.abspath(path)) or '.'
    try:
        os.makedirs(target, exist_ok=True)
    except OSError as exc:
        _die('create directory', target, exc)


def pin_stdout_utf8() -> None:
    """Best-effort UTF-8 stdout.

    Safe to call from any module and any number of times: it is a no-op when
    stdout already speaks UTF-8 (or cannot be wrapped, e.g. under a test
    harness that replaced sys.stdout).
    """
    stream = sys.stdout
    encoding = (getattr(stream, 'encoding', '') or '').lower().replace('-', '')
    if encoding.startswith('utf8'):
        return
    buffer = getattr(stream, 'buffer', None)
    if buffer is None:
        return
    with contextlib.suppress(AttributeError, ValueError):
        sys.stdout = io.TextIOWrapper(buffer, encoding='utf-8', line_buffering=True)
